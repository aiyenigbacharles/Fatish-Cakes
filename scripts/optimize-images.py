#!/usr/bin/env python3
"""
Image pipeline for Fatish Cakes.

Reads original photos from  assets-src/aistudio/*.png|jpg|jpeg|webp
Writes (served by the site):
  public/assets/img/<name>-<width>.webp   responsive WebP variants
  public/assets/og/<name>.jpg             social-share (Open Graph) JPEG
  src/data/imageManifest.ts               sizes + tiny blur placeholders

Usage:  pip install Pillow  &&  python3 scripts/optimize-images.py
Re-run any time you add or replace a photo in assets-src/aistudio/.
"""
import base64, io, json, os, sys
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets-src" / "aistudio"
OUT_IMG = ROOT / "public" / "assets" / "img"
OUT_OG = ROOT / "public" / "assets" / "og"
MANIFEST = ROOT / "src" / "data" / "imageManifest.ts"

WIDTHS = [320, 560, 800, 1200]   # never upscaled; original width is added if smaller
WEBP_QUALITY = 80
EXTS = {".png", ".jpg", ".jpeg", ".webp"}

def blur_placeholder(im: Image.Image) -> str:
    t = im.copy()
    t.thumbnail((24, 24), Image.LANCZOS)
    buf = io.BytesIO()
    t.convert("RGB").save(buf, "WEBP", quality=40, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()

def main():
    OUT_IMG.mkdir(parents=True, exist_ok=True)
    OUT_OG.mkdir(parents=True, exist_ok=True)
    manifest = {}
    total_in = total_out = 0
    for f in sorted(SRC.iterdir()):
        if f.suffix.lower() not in EXTS:
            continue
        name = f.stem
        im = ImageOps.exif_transpose(Image.open(f))
        has_alpha = im.mode in ("RGBA", "LA") or "transparency" in im.info
        im = im.convert("RGBA" if has_alpha else "RGB")
        w, h = im.size
        widths = sorted({x for x in WIDTHS if x < w} | {w})
        for tw in widths:
            th = round(h * tw / w)
            r = im if tw == w else im.resize((tw, th), Image.LANCZOS)
            out = OUT_IMG / f"{name}-{tw}.webp"
            r.save(out, "WEBP", quality=WEBP_QUALITY, method=6)
            total_out += out.stat().st_size
        og = OUT_OG / f"{name}.jpg"
        im.convert("RGB").save(og, "JPEG", quality=82, optimize=True, progressive=True)
        total_in += f.stat().st_size
        manifest[name] = {"w": w, "h": h, "widths": widths, "blur": blur_placeholder(im)}
        print(f"{f.name}: {f.stat().st_size/1024:.0f} KB -> {len(widths)} webp variants")

    ts = (
        "// AUTO-GENERATED by scripts/optimize-images.py. Do not edit by hand.\n"
        "export interface ImageMeta { w: number; h: number; widths: number[]; blur: string }\n"
        "export const imageManifest: Record<string, ImageMeta> = "
        + json.dumps(manifest, indent=2) + ";\n"
    )
    MANIFEST.write_text(ts, encoding="utf-8")
    print(f"\nOriginals: {total_in/1e6:.1f} MB  ->  all WebP variants: {total_out/1e6:.1f} MB")

if __name__ == "__main__":
    main()
